module TwitterCldr
  module Resources
    module Properties

      # Generates lib/twitter_cldr/shared/properties/bidi_paired_brackets.rb from
      # BidiBrackets.txt so that the bidirectional paired bracket mapping used
      # by UAX #9 rule BD16 matches the shipped Unicode data version.
      class BidiPairedBracketsImporter < Importer
        DATA_FILE = 'ucd/BidiBrackets.txt'
        OUTPUT_FILE = File.join(
          '..', 'lib', 'twitter_cldr', 'shared', 'properties',
          'bidi_paired_brackets.rb'
        )

        requirement :unicode, Versions.unicode_version, [DATA_FILE]
        output_path File.join(TwitterCldr::SPEC_DIR, 'bidi')
        ruby_engine :mri

        def execute
          entries = parse_bidi_brackets
          File.write(output_file, render(entries))
        end

        private

        def source_path
          requirements[:unicode].source_path_for(DATA_FILE)
        end

        def output_file
          File.expand_path(OUTPUT_FILE, File.join(TwitterCldr::SPEC_DIR, 'bidi'))
        end

        def parse_bidi_brackets
          entries = []
          File.foreach(source_path) do |line|
            line = line.sub(/#.*$/, '').strip
            next if line.empty?
            fields = line.split(';').map(&:strip)
            next unless fields[2] == 'o'
            entries << [fields[0].to_i(16), fields[1].to_i(16)]
          end
          entries
        end

        def render(entries)
          lines = entries.map do |open, close|
            "          0x#{open.to_s(16).upcase.rjust(4, '0')} => 0x#{close.to_s(16).upcase.rjust(4, '0')},"
          end

          <<~RUBY
            # encoding: UTF-8

            # Copyright 2012 Twitter, Inc
            # http://www.apache.org/licenses/LICENSE-2.0

            # This file is generated by BidiPairedBracketsImporter from
            # BidiBrackets.txt (Unicode #{Versions.unicode_version}).

            module TwitterCldr
              module Shared
                module Properties
                  module BidiPairedBrackets
                    OPEN_TO_CLOSE = {
            #{lines.join("\n")}
                    }.freeze

                    CLOSE_TO_OPEN = OPEN_TO_CLOSE.each_with_object({}) do |(open, close), memo|
                      memo[close] = open
                    end.freeze

                    class << self
                      def close_for_open(code_point)
                        OPEN_TO_CLOSE[code_point]
                      end

                      def open_for_close(code_point)
                        CLOSE_TO_OPEN[code_point]
                      end

                      def paired?(code_point)
                        OPEN_TO_CLOSE.key?(code_point) || CLOSE_TO_OPEN.key?(code_point)
                      end

                      def opening?(code_point)
                        OPEN_TO_CLOSE.key?(code_point)
                      end

                      def closing?(code_point)
                        CLOSE_TO_OPEN.key?(code_point)
                      end
                    end
                  end
                end
              end
            end
          RUBY
        end
      end

    end
  end
end
